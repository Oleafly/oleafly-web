/**
 * Translate English UI dictionary into all locales and rewrite src/i18n/ui/index.ts
 * partials with complete dictionaries (still falls back to en for missing keys).
 *
 * node scripts/translate-ui-locales.mjs
 * node scripts/translate-ui-locales.mjs --locales=es,fr,de,ja,zh-cn
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { translate } from "google-translate-api-x";
import { pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const TO_CODE = {
  es: "es", "pt-br": "pt", fr: "fr", de: "de", it: "it", nl: "nl", pl: "pl",
  ru: "ru", uk: "uk", tr: "tr", ar: "ar", hi: "hi", "zh-cn": "zh-CN",
  "zh-tw": "zh-TW", ja: "ja", ko: "ko", vi: "vi",
};

const ALL = Object.keys(TO_CODE);
const args = process.argv.slice(2);
const localesArg = args.find((a) => a.startsWith("--locales="));
const LOCALES = localesArg
  ? localesArg.split("=")[1].split(",").map((s) => s.trim())
  : ALL;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function tr(text, to) {
  if (!text?.trim()) return text;
  // Don't translate brand / technical tokens alone
  if (/^Oleafly|GitHub|LaTeX|Typst|Markdown|BibTeX|KaTeX|SyncTeX|RSS|PDF|DOI|arXiv|AGPL/i.test(text) && text.length < 20) {
    return text;
  }
  for (let i = 0; i < 4; i++) {
    try {
      const r = await translate(text, { to: TO_CODE[to] || to, forceTo: true });
      return r.text;
    } catch (e) {
      await sleep(600 * (i + 1));
    }
  }
  return text;
}

async function loadEn() {
  // Dynamic import of compiled-ish: parse en.ts as text
  return JSON.parse(await readFile(path.join(root, "src/i18n/ui/en.json"), "utf8"));
}

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
}

async function main() {
  const en = await loadEn();
  const keys = Object.keys(en);
  console.log(`English keys: ${keys.length}`);
  console.log(`Locales: ${LOCALES.join(", ")}`);

  /** @type {Record<string, Record<string, string>>} */
  const all = {};

  for (const locale of LOCALES) {
    console.log(`\n→ ${locale}`);
    all[locale] = {};
    let i = 0;
    for (const key of keys) {
      i++;
      const src = en[key];
      process.stdout.write(`  [${i}/${keys.length}] ${key.slice(0, 40)}… `);
      const out = await tr(src, locale);
      all[locale][key] = out;
      console.log("ok");
      await sleep(300);
    }
  }

  // Emit as TS module that only overrides (full dict via d() merge)
  // We'll write src/i18n/ui/generated.ts
  let out = `/* Auto-generated by scripts/translate-ui-locales.mjs — do not edit by hand */\n`;
  out += `import type { UiDict } from "./en";\n\n`;
  out += `export const generatedOverrides: Record<string, Partial<UiDict>> = {\n`;
  for (const locale of LOCALES) {
    out += `  ${JSON.stringify(locale)}: {\n`;
    for (const [k, v] of Object.entries(all[locale])) {
      // only store if different from en to keep file smaller? store all for completeness
      out += `    ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`;
    }
    out += `  },\n`;
  }
  out += `};\n`;

  const dest = path.join(root, "src/i18n/ui/generated.ts");
  await writeFile(dest, out, "utf8");
  console.log("\nWrote", dest);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
